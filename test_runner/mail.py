"""
Emails a summary of a test run through Outlook (the same way validate.py sends its report mail).

The mail has: a verdict and result counts, the run details, one row per test case, what failed and
why (failing step, error, expected result), test cases that could not be run, and a note on any
AI-generated plans (new / reused, verified or not, steps the AI repaired). The run summary or
evidence documents are attached.

    python -m test_runner TWC5958-T1218                 mails config.EMAIL_RECIPIENT afterwards
    python -m test_runner TWC5958-T1218 --no-email      no mail
    python -m test_runner TWC5958-T1218 --email-to someone@intel.com
    python -m test_runner TWC5958-T1218 --email-preview write the mail as an .html file, send nothing

A mail problem never changes the test result; the HTML is saved next to the results instead.
"""

from __future__ import annotations

import getpass
import html
import os
from datetime import datetime
from pathlib import Path

from . import config
from .summary import NOT_RUN, RunSummary, _counts, _duration, _failed_step, _name, _overall, _result_text, _steps

_COLORS = {            # status: (text, background)
    "PASS": ("#1e7e34", "#e3f4e8"),
    "FAIL": ("#b71c1c", "#fbe3e5"),
    "PARTIAL": ("#9a5b00", "#fff1dc"),
    "NOT_AUTOMATED": ("#555555", "#eeeeee"),
    "NO_DATA": ("#9a5b00", "#fff1dc"),
    NOT_RUN: ("#555555", "#eeeeee"),
}
_LABEL = {"PASS": "PASS", "FAIL": "FAIL", "PARTIAL": "PARTIAL", "NOT_AUTOMATED": "MANUAL",
          "NO_DATA": "NO DATA", NOT_RUN: "NOT RUN"}
_MAX_ATTACH_BYTES = 15 * 1024 * 1024


def _e(value) -> str:
    return html.escape(str(value if value is not None else ""), quote=True)


def _badge(status: str) -> str:
    color, background = _COLORS.get(status, _COLORS[NOT_RUN])
    return (f'<span style="display:inline-block;padding:2px 8px;border-radius:3px;font-weight:bold;'
            f'font-size:9pt;color:{color};background:{background};">{_e(_LABEL.get(status, status))}</span>')


def _cell(text, bold=False, width=None, bg=None, color="#333333") -> str:
    style = f"padding:6px 8px;border:1px solid #d0d7de;font-size:10pt;color:{color};vertical-align:top;"
    if bold:
        style += "font-weight:bold;"
    if bg:
        style += f"background:{bg};"
    if width:
        style += f"width:{width};"
    return f'<td style="{style}">{text}</td>'


def _head(*names) -> str:
    cells = "".join(f'<th align="left" style="padding:6px 8px;border:1px solid #1f4e79;background:#1f4e79;'
                    f'color:#ffffff;font-size:10pt;">{_e(n)}</th>' for n in names)
    return f"<tr>{cells}</tr>"


def _title(text: str) -> str:
    return (f'<h3 style="font-family:Arial,sans-serif;color:#1f4e79;font-size:12pt;margin:22px 0 6px 0;">'
            f'{_e(text)}</h3>')


# ----------------------------------------------------------------------------- facts

def _ai_note(entry) -> str:
    """One line about the AI plan behind a test case, or ''."""
    test_case = entry.test_case
    if test_case is None or not test_case.raw.get("ai_generated"):
        return ""
    parts = []
    generated_at = test_case.raw.get("generated_at")
    parts.append(f"plan generated by AI{' on ' + str(generated_at)[:16].replace('T', ' ') if generated_at else ''}")
    verified_at = test_case.raw.get("verified_at")
    if verified_at:
        parts.append(f"verified by a passing run ({str(verified_at)[:16].replace('T', ' ')})")
    else:
        parts.append("NOT yet verified by a passing run - a failure may be the plan's fault")
    repaired = sum(1 for s in test_case.steps if s.repaired)
    if repaired:
        parts.append(f"{repaired} step(s) were repaired by the AI during this run")
    return "; ".join(parts) + "."


def _failure_block(entry) -> str:
    test_case = entry.test_case
    step = _failed_step(test_case)
    if step is None:
        return ""
    failed = next((r for r in step.action_results if r.status == "FAIL"), None)
    rows = [("Step", f"{step.sequence}. {step.step.strip()[:400]}")]
    if failed is not None:
        rows.append(("Failed action", f"#{failed.index} {failed.action}"
                     + (f" - {failed.description}" if failed.description else "")))
        rows.append(("Error", failed.message))
    else:
        rows.append(("Error", (step.actual_result or "").split("\n")[0]))
    if step.expected_result.strip():
        rows.append(("Expected", step.expected_result.strip()[:400]))
    body = "".join(f"<tr>{_cell(_e(k), bold=True, width='110px', bg='#f6f8fa')}{_cell(_e(v))}</tr>"
                   for k, v in rows)
    return (f'<p style="font-family:Arial,sans-serif;font-size:10pt;margin:14px 0 4px 0;">'
            f'<b>{_e(entry.label)}</b> {_e(_name(entry))}</p>'
            f'<table cellpadding="0" cellspacing="0" style="border-collapse:collapse;width:100%;">{body}</table>')


# ----------------------------------------------------------------------------- the mail

def build_email(run: RunSummary, summary_docx: Path | None = None) -> tuple[str, str, list[Path]]:
    """(subject, html body, attachments) for a finished run."""
    finished = run.finished or datetime.now()
    count = _counts(run.entries)
    overall = _overall(count)
    seconds = int((finished - run.started).total_seconds())
    duration = f"{seconds // 60}m {seconds % 60:02d}s"

    if count["total"] == 1:
        what = run.entries[0].label
    else:
        what = f"{count['total']} test cases"
    subject = f"[{_LABEL.get(overall, overall)}] Test Execution Summary - {what} - {run.started:%d %b %Y}"

    verdict_color, verdict_bg = _COLORS.get(overall, _COLORS[NOT_RUN])
    if count["total"] == 1:
        sentence = f"{run.entries[0].label} finished with result <b>{_e(_LABEL.get(run.entries[0].status))}</b>."
    else:
        sentence = (f"<b>{count['PASS']} of {count['testable']}</b> testable cases passed ({count['rate']}). "
                    f"{count['FAIL']} failed" + (f", {count[NOT_RUN]} could not be run" if count[NOT_RUN] else "")
                    + (f", {count['NO_DATA']} returned no report data" if count["NO_DATA"] else "")
                    + (f", {count['PARTIAL'] + count['NOT_AUTOMATED']} need manual steps"
                       if count["PARTIAL"] + count["NOT_AUTOMATED"] else "") + ".")

    sites = sorted({e.test_case.app_url for e in run.entries if e.test_case})
    details = [("Scope", run.command), ("Application tested", ", ".join(sites) or "-"),
               ("Executed by", f"{getpass.getuser()} on {os.environ.get('COMPUTERNAME', '-')}"),
               ("Started", f"{run.started:%d %b %Y %H:%M:%S}"), ("Finished", f"{finished:%d %b %Y %H:%M:%S}"),
               ("Duration", duration)]
    details_html = "".join(f"<tr>{_cell(_e(k), bold=True, width='150px', bg='#f6f8fa')}{_cell(_e(v))}</tr>"
                           for k, v in details)

    tiles = "".join(
        f'<td align="center" style="padding:8px 14px;border:1px solid #d0d7de;background:{_COLORS[s][1]};">'
        f'<div style="font-size:18pt;font-weight:bold;color:{_COLORS[s][0]};">{count[s]}</div>'
        f'<div style="font-size:8pt;color:#555555;">{_LABEL[s]}</div></td>'
        for s in ("PASS", "FAIL", "PARTIAL", "NOT_AUTOMATED", "NO_DATA", NOT_RUN))

    rows = []
    for entry in run.entries:
        url = entry.test_case.raw.get("url") if entry.test_case else ""
        ident = f'<a href="{_e(url)}" style="color:#1f4e79;">{_e(entry.label)}</a>' if url else _e(entry.label)
        rows.append("<tr>" + _cell(f"<b>{ident}</b>") + _cell(_e(_name(entry))) + _cell(_badge(entry.status))
                    + _cell(_e(_steps(entry.test_case))) + _cell(_e(_duration(entry.test_case)).replace(" ", "&nbsp;"))
                    + _cell(_e(_result_text(entry))) + "</tr>")
    results = (f'<table cellpadding="0" cellspacing="0" style="border-collapse:collapse;width:100%;">'
               f'{_head("Test case", "Name", "Result", "Steps passed", "Time", "Outcome")}{"".join(rows)}</table>')

    failures = [e for e in run.entries if e.status == "FAIL" and e.test_case]
    failure_html = (_title("Needs attention") + "".join(_failure_block(e) for e in failures)) if failures else ""

    not_run = [e for e in run.entries if e.status == NOT_RUN]
    not_run_html = ""
    if not_run:
        items = "".join(f"<tr>{_cell(_e(e.label), bold=True)}{_cell(_e(e.reason))}</tr>" for e in not_run)
        not_run_html = (_title("Not executed") + '<table cellpadding="0" cellspacing="0" '
                        f'style="border-collapse:collapse;width:100%;">{_head("Test case / source", "Reason")}{items}</table>')

    no_data = [e for e in run.entries if e.status == "NO_DATA"]
    no_data_html = ""
    if no_data:
        items = "".join(f"<tr>{_cell(_e(e.label), bold=True)}{_cell(_e(_result_text(e)))}</tr>"
                        for e in no_data)
        no_data_html = (_title("Reports with no data") + '<table cellpadding="0" cellspacing="0" '
                        f'style="border-collapse:collapse;width:100%;">{_head("Test case", "Result")}{items}</table>')

    ai_lines = [(e.label, _ai_note(e)) for e in run.entries if _ai_note(e)]
    ai_html = ""
    if ai_lines:
        items = "".join(f"<tr>{_cell(_e(label), bold=True, width='150px')}{_cell(_e(note))}</tr>"
                        for label, note in ai_lines)
        ai_html = (_title("AI-generated plans") + '<p style="font-family:Arial,sans-serif;font-size:10pt;'
                   'color:#555555;margin:0 0 6px 0;">These test cases were converted from plain-English Jira '
                   'steps by the AI. A plan that has not passed a full run yet should be reviewed before a '
                   'failure is reported as an application defect.</p>'
                   f'<table cellpadding="0" cellspacing="0" style="border-collapse:collapse;width:100%;">{items}</table>')

    attachments, skipped = plan_attachments(run, summary_docx)
    attach_text = ("<br>".join(_e(p.name) for p in attachments) if attachments
                   else "None (see the evidence folder).")
    if skipped:
        attach_text += ('<br><br><span style="color:#b71c1c;">Not attached: '
                        + "; ".join(f"{_e(name)} ({_e(why)})" for name, why in skipped)
                        + ". Find them in the evidence folder.</span>")
    evidence_dirs = sorted({str(e.evidence.parent) for e in run.entries if e.evidence})

    body = f"""<html><body style="margin:0;padding:0;background:#ffffff;">
<table cellpadding="0" cellspacing="0" width="100%"><tr><td align="left" style="padding:16px;">
<table cellpadding="0" cellspacing="0" style="width:760px;max-width:100%;font-family:Arial,sans-serif;color:#333333;">
<tr><td style="padding:0 0 4px 0;font-size:18pt;font-weight:bold;color:#1f4e79;">Test Execution Summary</td></tr>
<tr><td style="padding:0 0 14px 0;font-size:10pt;color:#555555;">{run.started:%d %B %Y}</td></tr>
<tr><td style="padding:10px 14px;background:{verdict_bg};border-left:5px solid {verdict_color};font-size:11pt;">
<b style="color:{verdict_color};">{_e(_LABEL.get(overall, overall))}</b> &nbsp; {sentence}</td></tr>
<tr><td style="padding:14px 0 0 0;"><table cellpadding="0" cellspacing="6"><tr>{tiles}</tr></table></td></tr>
<tr><td>{_title("Run details")}<table cellpadding="0" cellspacing="0" style="border-collapse:collapse;width:100%;">{details_html}</table></td></tr>
<tr><td>{_title("Results")}{results}</td></tr>
<tr><td>{failure_html}</td></tr>
<tr><td>{no_data_html}</td></tr>
<tr><td>{not_run_html}</td></tr>
<tr><td>{ai_html}</td></tr>
<tr><td>{_title("Evidence")}<p style="font-size:10pt;margin:0;">Attached:<br>{attach_text}</p>
<p style="font-size:9pt;color:#555555;margin:8px 0 0 0;">Full evidence (screenshots, results JSON) is kept in:<br>{_e('; '.join(evidence_dirs) or str(config.OUTPUT_DIR))}</p></td></tr>
<tr><td style="padding:22px 0 0 0;font-size:10pt;">Regards,<br>Automated Test Runner</td></tr>
</table></td></tr></table></body></html>"""
    return subject, body, attachments


def plan_attachments(run: RunSummary, summary_docx: Path | None) -> tuple[list[Path], list[tuple[str, str]]]:
    """(attached, left out). Attached: the summary (group run) or evidence (single run) document plus
    the evidence of EVERY failed case, as far as the size limit allows. Left out: (file name, reason)."""
    wanted: list[Path] = []
    if summary_docx is not None:
        wanted.append(Path(summary_docx))
    elif len([e for e in run.entries if e.evidence]) == 1:
        wanted.append(next(e.evidence for e in run.entries if e.evidence))
    wanted += [e.evidence for e in run.entries if e.status in ("FAIL", "NO_DATA") and e.evidence]

    chosen, skipped, total = [], [], 0
    for path in dict.fromkeys(wanted):
        if not path.exists():
            skipped.append((path.name, "file not found"))
        elif total + path.stat().st_size > _MAX_ATTACH_BYTES:
            skipped.append((path.name, f"over the {_MAX_ATTACH_BYTES // (1024 * 1024)} MB mail size limit"))
        else:
            chosen.append(path)
            total += path.stat().st_size
    return chosen, skipped


def attachment_list(run: RunSummary, summary_docx: Path | None) -> list[Path]:
    return plan_attachments(run, summary_docx)[0]


def send(subject: str, body: str, to: str, attachments: list[Path], outlook=None) -> None:
    """Send through Outlook (Outlook.Application, like validate.py). Raises on failure."""
    if outlook is None:
        import win32com.client as win32      # only needed when a mail is actually sent
        outlook = win32.Dispatch("Outlook.Application")
    mail = outlook.CreateItem(0)
    mail.To = to
    mail.Subject = subject
    mail.HTMLBody = body
    for path in attachments:
        mail.Attachments.Add(str(path))
    mail.Send()


def email_run(run: RunSummary, output_dir: Path, summary_docx: Path | None = None, to: str | None = None,
              preview_only: bool = False) -> bool:
    """Build and send the run summary. Never raises; returns True if it was sent (or previewed)."""
    run.finished = run.finished or datetime.now()
    recipient = to or config.EMAIL_RECIPIENT
    try:
        subject, body, attachments = build_email(run, summary_docx)
    except Exception as e:
        print(f"Email: could not build the summary mail - {type(e).__name__}: {e}")
        return False

    output_dir.mkdir(parents=True, exist_ok=True)
    saved = output_dir / f"Summary_email_{run.started:%Y%m%d_%H%M%S}.html"
    saved.write_text(body, encoding="utf-8")
    if preview_only:
        print(f"Email preview (not sent): {saved}\n  To: {recipient}\n  Subject: {subject}")
        return True
    try:
        print(f"Sending summary mail to {recipient} ...", flush=True)
        send(subject, body, recipient, attachments)
    except Exception as e:
        print(f"Email: NOT sent - {type(e).__name__}: {e}\n  The mail was saved as {saved} so it can be sent by hand.")
        return False
    print(f"Summary mail sent to {recipient} ({len(attachments)} attachment(s)).")
    return True
